-- ============================================================================
--  AUTH TRIGGER — create public.users row on signup
--  Sign up with: supabase.auth.signUp({ email, password,
--                 options: { data: { username, role } } })
-- ============================================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
  v_role     text := coalesce(new.raw_user_meta_data ->> 'role', 'job_seeker');
  v_username text := coalesce(new.raw_user_meta_data ->> 'username',
                              split_part(new.email, '@', 1));
begin
  if v_role not in ('job_seeker', 'employer') then
    v_role := 'job_seeker';
  end if;

  begin
    insert into public.users (user_id, username, email, role)
    values (new.id, v_username, new.email, v_role);
  exception when unique_violation then
    insert into public.users (user_id, username, email, role)
    values (new.id, v_username || '_' || substr(new.id::text, 1, 6), new.email, v_role);
  end;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

