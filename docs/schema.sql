drop policy if exists "resume files employer read" on storage.objects;
create policy "resume files employer read" on storage.objects for select
  using (
    bucket_id = 'resumes'
    and exists (
      select 1
      from public.resumes r
      join public.applications a on a.resume_id = r.resume_id
      join public.job_posting j on j.job_id = a.job_id
      where r.resume_file = storage.objects.name
        and j.employer_id = public.current_employer_id()
    )
  );
create policy "resume files owner write" on storage.objects for insert
  with check (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "resume files owner delete" on storage.objects for delete
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = auth.uid()::text);

