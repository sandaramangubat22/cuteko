-- ============================================================================
--  JOB PORTAL — Supabase / PostgreSQL schema
--  Derived from docs/job-portal-ERD.mwb (schema: job_portal, Draft 2)
--  Run this in Supabase → SQL Editor → New query → Run
-- ============================================================================
--  Deviations from the MySQL ERD (all intentional, documented in ERD-REVIEW.md):
--    * USERS.password        -> removed; Supabase Auth stores hashes in auth.users
--    * USERS.user_id         -> uuid, references auth.users(id)
--    * COMPANIES.owner_id    -> added (uuid) so RLS can identify the company owner
--    * EDUCATIONS.education_id -> added as PK (ERD had no PK)
--    * datetime -> timestamptz, tinyint -> boolean, year -> smallint
--    * every FK now has an explicit ON DELETE rule
-- ============================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- 1. USERS  (public mirror of auth.users)
-- ---------------------------------------------------------------------------
create table if not exists public.users (
  user_id         uuid primary key references auth.users (id) on delete cascade,
  username        varchar(100) not null unique,
  email           varchar(150) not null unique,
  phone_number    varchar(20),
  role            varchar(50)  not null default 'job_seeker'
                    check (role in ('job_seeker', 'employer', 'admin')),
  profile_picture varchar(255),
  date_registered timestamptz  not null default now(),
  account_status  varchar(50)  not null default 'active'
                    check (account_status in ('active', 'inactive', 'suspended'))
);

-- ---------------------------------------------------------------------------
-- 2. COMPANIES
-- ---------------------------------------------------------------------------
create table if not exists public.companies (
  company_id          bigint generated by default as identity primary key,
  owner_id            uuid not null references public.users (user_id) on delete cascade,
  company_name        varchar(150) not null,
  company_address     varchar(255) not null,
  industry            varchar(100) not null,
  company_description text,
  contact_email       varchar(150) not null,
  contact_number      varchar(20)  not null,
  company_website     varchar(150) not null,
  company_status      varchar(50)  not null default 'active'
                        check (company_status in ('active', 'inactive', 'pending', 'suspended')),
  date_registered     timestamptz  not null default now()
);

create index if not exists companies_owner_idx on public.companies (owner_id);

-- keep 'suspended' valid even if the table was created by an older revision
alter table public.companies drop constraint if exists companies_company_status_check;
alter table public.companies add constraint companies_company_status_check
  check (company_status in ('active', 'inactive', 'pending', 'suspended'));

-- ---------------------------------------------------------------------------
-- 3. EMPLOYERS
-- ---------------------------------------------------------------------------
create table if not exists public.employers (
  employer_id  bigint generated by default as identity primary key,
  user_id      uuid   not null unique references public.users (user_id) on delete cascade,
  company_id   bigint not null references public.companies (company_id) on delete cascade,
  first_name   varchar(100) not null,
  last_name    varchar(100) not null,
  position     varchar(100) not null,
  phone_number varchar(20)  not null,
  date_joined  timestamptz  not null default now()
);

create index if not exists employers_company_idx on public.employers (company_id);

-- ---------------------------------------------------------------------------
-- 4. JOB_SEEKERS
-- ---------------------------------------------------------------------------
create table if not exists public.job_seekers (
  seeker_id    bigint generated by default as identity primary key,
  user_id      uuid   not null unique references public.users (user_id) on delete cascade,
  first_name   varchar(100) not null,
  last_name    varchar(100) not null,
  middle_name  varchar(100),
  address      varchar(255) not null,
  phone_number varchar(20)  not null,
  date_of_birth date,
  education    varchar(255),
  skills       text,
  experience   text,
  bio          text
);

-- ---------------------------------------------------------------------------
-- 5. RESUMES
-- ---------------------------------------------------------------------------
create table if not exists public.resumes (
  resume_id       bigint generated by default as identity primary key,
  seeker_id       bigint not null references public.job_seekers (seeker_id) on delete cascade,
  resume_title    varchar(150) not null,
  work_experience text,
  certifications  text,
  resume_file     varchar(255),
  date_created    timestamptz  not null default now(),
  is_default      boolean      not null default false
);

create index if not exists resumes_seeker_idx on public.resumes (seeker_id);
-- only one default resume per seeker
create unique index if not exists resumes_one_default_idx
  on public.resumes (seeker_id) where is_default;

-- ---------------------------------------------------------------------------
-- 6. EDUCATIONS
-- ---------------------------------------------------------------------------
create table if not exists public.educations (
  education_id bigint generated by default as identity primary key,
  seeker_id    bigint not null references public.job_seekers (seeker_id) on delete cascade,
  school_level varchar(50),
  school_name  varchar(150),
  degree       varchar(150),
  year_started smallint,
  year_ended   smallint,
  date_created timestamptz not null default now()
);

create index if not exists educations_seeker_idx on public.educations (seeker_id);

-- ---------------------------------------------------------------------------
-- 7. SKILLS
-- ---------------------------------------------------------------------------
create table if not exists public.skills (
  skill_id         bigint generated by default as identity primary key,
  seeker_id        bigint not null references public.job_seekers (seeker_id) on delete cascade,
  skill_name       varchar(100) not null,
  skill_category   varchar(100),
  proficiency_level varchar(50)
