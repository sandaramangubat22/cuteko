create index if not exists feedback_status_idx on public.feedback (feedback_status);
create index if not exists feedback_date_idx   on public.feedback (date_sent desc);

-- ============================================================================
--  HELPERS — security definer so RLS policies don't recurse
-- ============================================================================
-- named auth_role() on purpose: current_role is a PostgreSQL keyword
create or replace function public.auth_role()
returns text
language sql stable security definer
set search_path = public
as $$
  select role from public.users where user_id = auth.uid();
$$;

create or replace function public.current_seeker_id()
returns bigint
language sql stable security definer
set search_path = public
as $$
  select seeker_id from public.job_seekers where user_id = auth.uid();
$$;

create or replace function public.current_employer_id()
returns bigint
language sql stable security definer
set search_path = public
as $$
  select employer_id from public.employers where user_id = auth.uid();
$$;

-- true when the given resume belongs to an applicant of one of my job posts
create or replace function public.employer_can_see_resume(p_resume_id bigint)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.applications a
    join public.job_posting j on j.job_id = a.job_id
    where a.resume_id = p_resume_id
      and j.employer_id = public.current_employer_id()
  );
$$;

-- true when the signed-in seeker applied to this job (lets them still read a closed posting)
create or replace function public.seeker_applied_to_job(p_job_id bigint)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.applications a
    where a.job_id = p_job_id
      and a.seeker_id = public.current_seeker_id()
  );
$$;

