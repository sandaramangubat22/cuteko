create index if not exists skills_seeker_idx on public.skills (seeker_id);

-- ---------------------------------------------------------------------------
-- 8. JOB_POSTING
-- ---------------------------------------------------------------------------
create table if not exists public.job_posting (
  job_id               bigint generated by default as identity primary key,
  company_id           bigint not null references public.companies (company_id) on delete cascade,
  employer_id          bigint not null references public.employers (employer_id) on delete cascade,
  job_title            varchar(150) not null,
  job_description      text,
  qualifications       text,
  skills_required      text,
  employment_type      varchar(50)  not null,
  salary_range         varchar(100),
  location             varchar(100) not null,
  date_posted          timestamptz  not null default now(),
  application_deadline date,
  job_status           varchar(50)  not null default 'open'
                         check (job_status in ('draft', 'open', 'closed'))
);

create index if not exists job_posting_company_idx  on public.job_posting (company_id);
create index if not exists job_posting_employer_idx on public.job_posting (employer_id);
create index if not exists job_posting_status_idx   on public.job_posting (job_status);

-- ---------------------------------------------------------------------------
-- 9. APPLICATIONS
-- ---------------------------------------------------------------------------
create table if not exists public.applications (
  application_id     bigint generated by default as identity primary key,
  seeker_id          bigint not null references public.job_seekers (seeker_id) on delete cascade,
  job_id             bigint not null references public.job_posting (job_id) on delete cascade,
  resume_id          bigint references public.resumes (resume_id) on delete set null,
  application_date   timestamptz not null default now(),
  application_status varchar(50) not null default 'pending'
                       check (application_status in
                         ('pending', 'reviewed', 'shortlisted', 'interview', 'rejected', 'hired')),
  cover_letter       text,
  constraint applications_unique_per_job unique (job_id, seeker_id)
